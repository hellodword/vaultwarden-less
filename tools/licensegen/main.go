// Command licensegen creates the deterministic third-party license inventory.
// It intentionally uses only the Go toolchain and the module source trees; no
// network or wall-clock metadata is written to the generated document.
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

type module struct {
	Path    string
	Version string
	Dir     string
	Main    bool
}

type license struct {
	Component string
	Version   string
	Text      string
	Source    string
}

func main() {
	output := "THIRD_PARTY_LICENSES.md"
	if len(os.Args) == 2 {
		output = os.Args[1]
	} else if len(os.Args) > 2 {
		fmt.Fprintln(os.Stderr, "usage: licensegen [output]")
		os.Exit(2)
	}
	modules, err := listModules()
	if err != nil {
		fatal(err)
	}
	licenses := make([]license, 0, len(modules))
	for _, item := range modules {
		if item.Main || item.Version == "" {
			continue
		}
		directory, err := moduleDirectory(item)
		if err != nil {
			fatal(err)
		}
		text, source, err := readLicense(directory)
		if err != nil {
			fatal(fmt.Errorf("module %s@%s: %w", item.Path, item.Version, err))
		}
		licenses = append(licenses, license{Component: item.Path, Version: item.Version, Text: text, Source: source})
	}
	sort.Slice(licenses, func(i, j int) bool {
		if licenses[i].Component == licenses[j].Component {
			return licenses[i].Version < licenses[j].Version
		}
		return licenses[i].Component < licenses[j].Component
	})
	nonGo, err := readNonGoLicenses()
	if err != nil {
		fatal(err)
	}
	var document strings.Builder
	document.WriteString("# Third-party licenses\n\n")
	document.WriteString("This file is generated by `tools/licensegen`. It contains the complete license text for the Go modules used by the Linux binaries and the pinned non-module inputs.\n\n")
	for _, item := range licenses {
		fmt.Fprintf(&document, "## %s %s\n\n", item.Component, item.Version)
		fmt.Fprintf(&document, "Source file: `%s`\n\n", item.Source)
		writeBlock(&document, item.Text)
	}
	for _, item := range nonGo {
		fmt.Fprintf(&document, "## %s\n\n", item.Component)
		fmt.Fprintf(&document, "Input SHA-256: `%s`\n\n", sha256Text(item.Text))
		writeBlock(&document, item.Text)
	}
	generated := strings.TrimRight(document.String(), "\n") + "\n"
	if err := os.WriteFile(output, []byte(generated), 0o644); err != nil {
		fatal(fmt.Errorf("write %s: %w", output, err))
	}
}

func listModules() ([]module, error) {
	command := exec.Command("go", "list", "-m", "-json", "all")
	output, err := command.Output()
	if err != nil {
		return nil, fmt.Errorf("go list modules: %w", err)
	}
	decoder := json.NewDecoder(bytes.NewReader(output))
	var result []module
	for {
		var item module
		err := decoder.Decode(&item)
		if err == io.EOF {
			return result, nil
		}
		if err != nil {
			return nil, fmt.Errorf("decode go module list: %w", err)
		}
		result = append(result, item)
	}
}

func moduleDirectory(item module) (string, error) {
	if item.Dir != "" {
		return item.Dir, nil
	}
	command := exec.Command("go", "mod", "download", "-json", item.Path+"@"+item.Version)
	output, err := command.Output()
	if err != nil {
		return "", fmt.Errorf("download module source: %w", err)
	}
	var downloaded struct{ Dir string }
	if err := json.Unmarshal(output, &downloaded); err != nil || downloaded.Dir == "" {
		return "", fmt.Errorf("module source directory is unavailable")
	}
	return downloaded.Dir, nil
}

func readLicense(directory string) (string, string, error) {
	entries, err := os.ReadDir(directory)
	if err != nil {
		return "", "", err
	}
	for _, entry := range entries {
		if entry.IsDir() {
			continue
		}
		name := strings.ToLower(entry.Name())
		if name != "license" && name != "license.md" && name != "license.txt" && name != "copying" && name != "copying.txt" && name != "notice" && name != "notice.txt" {
			continue
		}
		path := filepath.Join(directory, entry.Name())
		data, err := os.ReadFile(path)
		if err != nil {
			return "", "", err
		}
		return normalize(string(data)), entry.Name(), nil
	}
	return "", "", fmt.Errorf("no license file found")
}

func readNonGoLicenses() ([]license, error) {
	entries, err := os.ReadDir("licenses/non-go")
	if err != nil {
		return nil, fmt.Errorf("read non-Go license inputs: %w", err)
	}
	items := make([]license, 0, len(entries))
	for _, entry := range entries {
		if entry.IsDir() {
			continue
		}
		data, err := os.ReadFile(filepath.Join("licenses/non-go", entry.Name()))
		if err != nil {
			return nil, err
		}
		items = append(items, license{Component: entry.Name(), Text: normalize(string(data))})
	}
	sort.Slice(items, func(i, j int) bool { return items[i].Component < items[j].Component })
	return items, nil
}

func normalize(value string) string {
	value = strings.ReplaceAll(value, "\r\n", "\n")
	value = strings.ReplaceAll(value, "\r", "\n")
	lines := strings.Split(strings.TrimSpace(value), "\n")
	for index := range lines {
		lines[index] = strings.TrimRight(lines[index], " \t")
	}
	return strings.Join(lines, "\n") + "\n"
}

func writeBlock(document *strings.Builder, text string) {
	document.WriteString("```text\n")
	document.WriteString(text)
	document.WriteString("```\n\n")
}

func sha256Text(value string) string {
	sum := sha256.Sum256([]byte(value))
	return hex.EncodeToString(sum[:])
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}
