"""Generate deterministic Go constants from the audited upstream inventory."""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

import tomllib
from project_metadata import vaultwarden_local_image

HEX_COMMIT = re.compile(r"[0-9a-f]{40}")
IMAGE_DIGEST = re.compile(r"sha256:[0-9a-f]{64}")
MIGRATION = re.compile(r"[0-9]{14}")
VERSION = re.compile(r"[0-9]+\.[0-9]+\.[0-9]+")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", type=Path, default=Path("UPSTREAMS.toml"))
    parser.add_argument(
        "--output", type=Path, default=Path("internal/upstream/generated.go")
    )
    return parser.parse_args()


def require(value: object, pattern: re.Pattern[str], name: str) -> str:
    if not isinstance(value, str) or not pattern.fullmatch(value):
        raise ValueError(f"{name} has an invalid value")
    return value


def quoted(value: str) -> str:
    if any(character in value for character in ('"', "\\", "\r", "\n", "\x00")):
        raise ValueError("generated string contains an unsupported character")
    return f'"{value}"'


def main() -> int:
    args = parse_args()
    try:
        data = tomllib.loads(args.input.read_text(encoding="utf-8"))
        vaultwarden = data["vaultwarden"]
        bitwarden = data["bitwarden_cli"]
        restic = data["restic"]
        moto = data["moto"]
        go = data["go"]
        contract_path = (
            args.input.parent / str(vaultwarden["schema_contract"])
        ).resolve()
        contract = json.loads(contract_path.read_text(encoding="utf-8"))
        if (
            contract.get("contract_version") != 1
            or contract.get("vaultwarden_version") != vaultwarden["version"]
            or contract.get("database_migration") != vaultwarden["database_migration"]
        ):
            raise ValueError(
                "Vaultwarden schema contract does not match UPSTREAMS.toml"
            )
        schema_fingerprint = require(
            contract.get("fingerprint"),
            IMAGE_DIGEST,
            "vaultwarden schema fingerprint",
        )
        audited_values = {
            "VaultwardenVersion": require(
                vaultwarden["version"], VERSION, "vaultwarden.version"
            ),
            "VaultwardenCommit": require(
                vaultwarden["source_commit"], HEX_COMMIT, "vaultwarden.source_commit"
            ),
            "VaultwardenMigration": require(
                vaultwarden["database_migration"],
                MIGRATION,
                "vaultwarden.database_migration",
            ),
            "VaultwardenImageRepository": str(vaultwarden["image_repository"]),
            "VaultwardenImageDigest": require(
                vaultwarden["image_digest"], IMAGE_DIGEST, "vaultwarden.image_digest"
            ),
            "VaultwardenSchemaFingerprint": schema_fingerprint,
            "BitwardenCLIVersion": require(
                bitwarden["version"], VERSION, "bitwarden_cli.version"
            ),
            "BitwardenCLICommit": require(
                bitwarden["source_commit"], HEX_COMMIT, "bitwarden_cli.source_commit"
            ),
            "ResticVersion": require(restic["version"], VERSION, "restic.version"),
            "ResticCommit": require(
                restic["source_commit"], HEX_COMMIT, "restic.source_commit"
            ),
            "MotoVersion": require(moto["version"], VERSION, "moto.version"),
            "MotoCommit": require(
                moto["source_commit"], HEX_COMMIT, "moto.source_commit"
            ),
            "GoVersion": require(go["version"], VERSION, "go.version"),
            "GoCommit": require(go["source_commit"], HEX_COMMIT, "go.source_commit"),
        }
        local_vaultwarden_tag = vaultwarden_local_image(
            audited_values["VaultwardenVersion"],
            audited_values["VaultwardenImageDigest"],
        )
        generated_values = {
            name: audited_values[name]
            for name in (
                "VaultwardenVersion",
                "VaultwardenMigration",
                "VaultwardenImageRepository",
                "VaultwardenImageDigest",
                "VaultwardenSchemaFingerprint",
                "ResticVersion",
                "MotoVersion",
            )
        }
        lines = [
            "// Code generated by scripts/generate_upstreams.py; DO NOT EDIT.",
            "",
            "// Package upstream exposes audited metadata consumed by product code.",
            "package upstream",
            "",
            "const (",
        ]
        for name, value in generated_values.items():
            lines.append(f"\t{name} = {quoted(value)}")
        lines.extend(
            [
                f"\tVaultwardenLocalImage = {quoted(local_vaultwarden_tag)}",
                ")",
                "",
            ]
        )
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    except (
        json.JSONDecodeError,
        KeyError,
        OSError,
        TypeError,
        ValueError,
        tomllib.TOMLDecodeError,
    ) as error:
        print(f"generate upstreams failed: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
